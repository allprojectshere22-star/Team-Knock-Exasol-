-- Step 2 - load the demo CSVs (about 10,000 records).
-- IMPORT ... FROM LOCAL CSV FILE reads files on YOUR machine; it works in EXAplus and other clients that support LOCAL imports.
-- Adjust the file paths (relative to the project root, where the client was started). If your client cannot do LOCAL imports,
-- use `python backend/leakagelens_cli.py --load data/demo_csv` instead, which loads the same files.

TRUNCATE TABLE LEAKAGELENS.FINDING_EVIDENCE;
TRUNCATE TABLE LEAKAGELENS.FINDINGS;

DELETE FROM LEAKAGELENS.SUPPLIERS;
IMPORT INTO LEAKAGELENS.SUPPLIERS (SUPPLIER_ID, SUPPLIER_NAME, NORMALIZED_SUPPLIER_NAME, CURRENCY, ACTIVE_STATUS)
FROM LOCAL CSV FILE 'data/demo_csv/suppliers.csv'
COLUMN SEPARATOR = ',' ROW SEPARATOR = 'LF' SKIP = 1;

DELETE FROM LEAKAGELENS.PURCHASE_ORDERS;
IMPORT INTO LEAKAGELENS.PURCHASE_ORDERS (PO_ID, SUPPLIER_ID, SUPPLIER_NAME, APPROVED_AMOUNT, CURRENCY, STATUS, CREATED_DATE)
FROM LOCAL CSV FILE 'data/demo_csv/purchase_orders.csv'
COLUMN SEPARATOR = ',' ROW SEPARATOR = 'LF' SKIP = 1;

DELETE FROM LEAKAGELENS.INVOICES;
IMPORT INTO LEAKAGELENS.INVOICES (INVOICE_ID, SUPPLIER_ID, SUPPLIER_NAME, INVOICE_NUMBER, PO_ID, INVOICE_DATE, DUE_DATE, AMOUNT, CURRENCY, DESCRIPTION)
FROM LOCAL CSV FILE 'data/demo_csv/invoices.csv'
COLUMN SEPARATOR = ',' ROW SEPARATOR = 'LF' SKIP = 1;

DELETE FROM LEAKAGELENS.PAYMENTS;
IMPORT INTO LEAKAGELENS.PAYMENTS (PAYMENT_ID, SUPPLIER_ID, INVOICE_ID, PAYMENT_DATE, AMOUNT, CURRENCY, STATUS, PAYMENT_REFERENCE, REVERSAL_OF)
FROM LOCAL CSV FILE 'data/demo_csv/payments.csv'
COLUMN SEPARATOR = ',' ROW SEPARATOR = 'LF' SKIP = 1;

DELETE FROM LEAKAGELENS.CREDIT_NOTES;
IMPORT INTO LEAKAGELENS.CREDIT_NOTES (CREDIT_ID, SUPPLIER_ID, INVOICE_ID, CREDIT_DATE, AMOUNT, CURRENCY, APPLIED, REASON)
FROM LOCAL CSV FILE 'data/demo_csv/credit_notes.csv'
COLUMN SEPARATOR = ',' ROW SEPARATOR = 'LF' SKIP = 1;

