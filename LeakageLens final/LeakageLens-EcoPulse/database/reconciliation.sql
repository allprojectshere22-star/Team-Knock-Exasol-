-- Per-invoice payable, unapplied credit, and settled non-reversal payment reconciliation.
WITH payment_totals AS (
    SELECT INVOICE_ID, SUM(AMOUNT) AS PAID
    FROM LEAKAGELENS.PAYMENTS
    WHERE STATUS = 'SETTLED' AND REVERSAL_OF IS NULL
    GROUP BY INVOICE_ID
), credit_totals AS (
    SELECT INVOICE_ID, SUM(CASE WHEN APPLIED = FALSE THEN AMOUNT ELSE 0 END) AS OPEN_CREDIT
    FROM LEAKAGELENS.CREDIT_NOTES GROUP BY INVOICE_ID
)
SELECT i.INVOICE_ID, i.PO_ID, i.AMOUNT AS INVOICE_AMOUNT,
       COALESCE(c.OPEN_CREDIT, 0) AS UNAPPLIED_CREDIT,
       i.AMOUNT - COALESCE(c.OPEN_CREDIT, 0) AS EXPECTED_PAYABLE,
       COALESCE(p.PAID, 0) AS SETTLED_PAYMENTS,
       COALESCE(p.PAID, 0) - (i.AMOUNT - COALESCE(c.OPEN_CREDIT, 0)) AS PAYMENT_VARIANCE
FROM LEAKAGELENS.INVOICES i
LEFT JOIN payment_totals p ON p.INVOICE_ID = i.INVOICE_ID
LEFT JOIN credit_totals c ON c.INVOICE_ID = i.INVOICE_ID
