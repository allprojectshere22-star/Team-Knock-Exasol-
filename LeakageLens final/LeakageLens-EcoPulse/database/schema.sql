CREATE SCHEMA IF NOT EXISTS LEAKAGELENS;

CREATE TABLE IF NOT EXISTS LEAKAGELENS.SUPPLIERS (
    SUPPLIER_ID VARCHAR(80) PRIMARY KEY, SUPPLIER_NAME VARCHAR(200),
    NORMALIZED_SUPPLIER_NAME VARCHAR(200), CURRENCY VARCHAR(3), ACTIVE_STATUS VARCHAR(30)
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.PURCHASE_ORDERS (
    PO_ID VARCHAR(80) PRIMARY KEY, SUPPLIER_ID VARCHAR(80), SUPPLIER_NAME VARCHAR(200),
    APPROVED_AMOUNT DECIMAL(18,2), CURRENCY VARCHAR(3), STATUS VARCHAR(30), CREATED_DATE DATE
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.INVOICES (
    INVOICE_ID VARCHAR(100) PRIMARY KEY, SUPPLIER_ID VARCHAR(80), SUPPLIER_NAME VARCHAR(200),
    INVOICE_NUMBER VARCHAR(120), PO_ID VARCHAR(80), INVOICE_DATE DATE, DUE_DATE DATE,
    AMOUNT DECIMAL(18,2), CURRENCY VARCHAR(3), DESCRIPTION VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.PAYMENTS (
    PAYMENT_ID VARCHAR(100) PRIMARY KEY, SUPPLIER_ID VARCHAR(80), INVOICE_ID VARCHAR(100),
    PAYMENT_DATE DATE, AMOUNT DECIMAL(18,2), CURRENCY VARCHAR(3), STATUS VARCHAR(30),
    PAYMENT_REFERENCE VARCHAR(200), REVERSAL_OF VARCHAR(100)
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.CREDIT_NOTES (
    CREDIT_ID VARCHAR(100) PRIMARY KEY, SUPPLIER_ID VARCHAR(80), INVOICE_ID VARCHAR(100),
    CREDIT_DATE DATE, AMOUNT DECIMAL(18,2), CURRENCY VARCHAR(3), APPLIED BOOLEAN, REASON VARCHAR(300)
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.AUDIT_RUNS (
    AUDIT_ID VARCHAR(36) PRIMARY KEY, STARTED_AT TIMESTAMP, COMPLETED_AT TIMESTAMP,
    STATUS VARCHAR(30), INVOICE_COUNT DECIMAL(18,0), PO_COUNT DECIMAL(18,0),
    PAYMENT_COUNT DECIMAL(18,0), CREDIT_COUNT DECIMAL(18,0), FINDING_COUNT DECIMAL(18,0),
    GROSS_FLAGGED DECIMAL(18,2), POTENTIAL_EXPOSURE DECIMAL(18,2), ERROR_MESSAGE VARCHAR(2000),
    QUERY_TIMINGS VARCHAR(2000)
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.FINDINGS (
    FINDING_ID VARCHAR(250) PRIMARY KEY, AUDIT_ID VARCHAR(36), CATEGORY VARCHAR(80),
    INVOICE_ID VARCHAR(100), PO_ID VARCHAR(250), PAYMENT_IDS VARCHAR(500), CREDIT_IDS VARCHAR(500),
    EXPECTED_AMOUNT DECIMAL(18,2), OBSERVED_AMOUNT DECIMAL(18,2), DIFFERENCE DECIMAL(18,2),
    CONFIDENCE DECIMAL(5,4), EXPLANATION VARCHAR(2000), NEXT_ACTION VARCHAR(1000),
    REVIEW_STATUS VARCHAR(30), REVIEW_NOTES VARCHAR(2000), EXPOSURE_AMOUNT DECIMAL(18,2),
    GROSS_AMOUNT DECIMAL(18,2), CONFIRMED_RECOVERY DECIMAL(18,2), CREATED_AT TIMESTAMP
);
CREATE TABLE IF NOT EXISTS LEAKAGELENS.FINDING_EVIDENCE (
    EVIDENCE_ID VARCHAR(250) PRIMARY KEY, FINDING_ID VARCHAR(250), EVIDENCE_TYPE VARCHAR(80),
    EVIDENCE_TEXT VARCHAR(2000), SOURCE_IDS VARCHAR(1000), CREATED_AT TIMESTAMP
);
